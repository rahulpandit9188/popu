export function tUI(medium) {
  return isHindi(medium) ? ui.Hindi : ui.English;
}

export function subjectLabel(name, medium) {
  if (!isHindi(medium)) return name;
  return subjectsHi[name] || name;
}

export function classLabel(name, medium) {
  if (!isHindi(medium)) return name;
  return classesHi[name] || name;
}

export function chapterTitle(chapter, medium) {
  if (!isHindi(medium)) return chapter.title;
  return titlesHi[chapter.title] || chapter.title;
}

export function chapterMeta(chapter, medium) {
  if (!isHindi(medium)) return chapter.meta;
  return String(chapter.meta)
    .replace(/Chapter/g, 'अध्याय')
    .replace(/Science/g, 'विज्ञान')
    .replace(/Beehive/g, 'बीहाइव')
    .replace(/Moments/g, 'मोमेंट्स');
}

export function chapterDescription(chapter, medium) {
  if (!isHindi(medium)) return chapter.description;
  const title = chapterTitle(chapter, 'Hindi');
  return `इस अध्याय में ${title} की मुख्य अवधारणाएँ, परिभाषाएँ, उदाहरण और परीक्षा के महत्वपूर्ण प्रश्न सरल भाषा में समझाए गए हैं।`;
}

export function subjectDescription(subject, medium) {
  if (!isHindi(medium)) return subject.description;
  const name = subjectLabel(subject.name, 'Hindi');
  return `${name} के अध्यायवार नोट्स, महत्वपूर्ण प्रश्न और परीक्षा सामग्री।`;
}

export function buildNotes(page, subject, chapter, medium) {
  const title = chapterTitle(chapter, medium);
  const className = classLabel(page.title, medium);
  const subjectName = subjectLabel(subject.name, medium);
  const description = chapterDescription(chapter, medium);
  const topics = chapter.description
    .split(/,| and /)
    .map((part) => part.replace(/\.$/, '').trim())
    .filter(Boolean);

  if (isHindi(medium)) {
    return {
      intro: `${title} ${className} के ${subjectName} का एक महत्वपूर्ण अध्याय है। ${description}`,
      points: topics.length
        ? topics.map((topic, index) => `बिंदु ${index + 1}: ${title} से संबंधित — ${topic}`)
        : [description],
      remember: [
        `${title} को छोटे नोट्स और चित्रों के साथ दोहराएँ।`,
        'पाठ्यपुस्तक के उदाहरण और संख्यात्मक प्रश्न हल करें।',
        'परिभाषाएँ और सूत्र अपनी भाषा में लिखकर याद करें।',
      ],
      questions: [
        `${title} का मुख्य विचार परिभाषित कीजिए।`,
        `${title} से कोई दो महत्वपूर्ण अवधारणाएँ समझाइए।`,
        `${title} से संबंधित एक दैनिक जीवन का उदाहरण लिखिए।`,
      ],
    };
  }

  return {
    intro: `${title} is an important ${subjectName} chapter for ${className}. ${description}`,
    points: topics.length
      ? topics.map((topic) => `${topic.charAt(0).toUpperCase()}${topic.slice(1)}`)
      : [description],
    remember: [
      `Revise ${title} with short notes and diagrams.`,
      'Practice numericals and textbook examples.',
      'Write definitions and formulas in your own words.',
    ],
    questions: [
      `Define the main idea of ${title}.`,
      `Explain any two important concepts from ${title}.`,
      `Write one daily-life example related to ${title}.`,
    ],
  };
}
